def pick_hints(items: Iterable[str], count: int = 12, seed: Any = "") -> List[str]:
    """从池子里随机取几条（不重复）；池子小于 count 时全给。"""
    values = [str(item) for item in items if str(item).strip()]
    count = max(1, min(int(count), len(values)))
    rnd = random.Random(str(seed))
    return rnd.sample(values, count)
